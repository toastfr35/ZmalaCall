// Copy approved artwork exactly, without a canvas runtime or geometric changes.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = (name) => fs.readFileSync(path.join(root, 'docs/branding/PNG', name));
const dark = source('a1-mark-dark-256.png');
const light = source('a1-mark-light-256.png');
const assets = new Map([
  ['zmala_server/assets/zmala-icon.png', dark],
  ['zmala_server/assets/zmala-icon-light.png', light],
  ['zmala_terminal/common/assets/zmala-icon.png', dark],
  ['zmala_terminal/common/assets/zmala-icon-light.png', light],
  ['zmala_phone/app/src/main/res/drawable-nodpi/zmala_brand_mark.png', dark],
  ['zmala_phone/app/src/main/res/drawable-nodpi/zmala_app_icon.png', source('a3-app-dark-512.png')],
  [
    'zmala_server/assets/zmala-icon.svg',
    Buffer.from(
      '<!-- Generated by build_tools/create-product-icon.cjs from approved A1 artwork. -->\n' +
        '<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256">' +
        '<image width="256" height="256" href="data:image/png;base64,' +
        dark.toString('base64') +
        '"/></svg>\n',
    ),
  ],
]);
for (const [relative, content] of assets) {
  const file = path.join(root, relative);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || !fs.readFileSync(file).equals(content))
      throw Error('Stale branding asset: ' + relative);
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
}
console.log(
  process.argv.includes('--check')
    ? 'Runtime logos match approved artwork.'
    : 'Runtime logos exported.',
);
